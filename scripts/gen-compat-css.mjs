// Older Android WebViews (Chrome 80, common on cheap phones) cannot do `gap` on flex layouts. This reads app.css and writes
// compat.css, which spaces the same containers with margins. It only applies when the app detects the missing support.
//   node scripts/gen-compat-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const css = readFileSync('public/css/app.css', 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const out = ['/* Generated by scripts/gen-compat-css.mjs. Spacing for browsers without flex "gap". Do not edit by hand. */'];
for (const m of css.matchAll(/([^{}@]+)\{([^{}]*)\}/g)) {
  const sel = m[1].trim();
  const body = m[2];
  const gap = /(?:^|[;\s])gap:\s*([^;]+)/.exec(body)?.[1].trim().split(/\s+/)[0];
  if (!gap || /^0(px)?$/.test(gap) || !/display:\s*(inline-flex|flex)\b/.test(body)) continue;
  const scoped = (suffix) => sel.split(',').map((s) => `html.no-fg ${s.trim()}${suffix}`).join(',\n');
  if (/flex-direction:\s*column/.test(body)) out.push(`${scoped(' > * + *')} { margin-top: ${gap}; }`);
  else if (/flex-wrap:\s*wrap/.test(body)) out.push(`${scoped(' > *')} { margin: 0 ${gap} ${gap} 0; }`);
  else {
    out.push(`${scoped(' > * + *')} { margin-left: ${gap}; }`);
    if (/inline-flex/.test(body)) out.push(`${scoped(' > svg:last-child')} { margin-right: ${gap}; }`); // an icon followed by plain text
  }
}
writeFileSync('public/css/compat.css', `${out.join('\n')}\n`);
console.log(`compat.css: ${out.length - 1} rules`);
